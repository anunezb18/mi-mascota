-- =====================================================================
--  MiMascota - Esquema relacional (PostgreSQL)
--  Se ejecuta automáticamente al crear el contenedor por primera vez.
--  Cambios posteriores al esquema se gestionan con Alembic (backend/).
-- =====================================================================

BEGIN;

-- Función genérica para mantener updated_at
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
--  Usuarios (adoptante, fundación, administrador)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    full_name      VARCHAR(150) NOT NULL,
    phone          VARCHAR(20),
    role           VARCHAR(20)  NOT NULL
                   CONSTRAINT ck_users_role CHECK (role IN ('adopter', 'foundation', 'admin')),
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
--  Fundaciones (cada una asociada a un usuario con rol 'foundation')
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS foundations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL UNIQUE
                 REFERENCES users(id) ON DELETE CASCADE,
    name         VARCHAR(150) NOT NULL,
    nit          VARCHAR(20)  UNIQUE,
    address      VARCHAR(255),
    city         VARCHAR(100),
    phone        VARCHAR(20),
    description  TEXT,
    is_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TRIGGER trg_foundations_updated_at
    BEFORE UPDATE ON foundations
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
--  Solicitudes de adopción
--  pet_id referencia el ObjectId (hex de 24 caracteres) en MongoDB.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS adoption_requests (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adopter_id     BIGINT      NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    foundation_id  BIGINT      NOT NULL REFERENCES foundations(id) ON DELETE RESTRICT,
    pet_id         CHAR(24)    NOT NULL
                   CONSTRAINT ck_adoption_requests_pet_id CHECK (pet_id ~ '^[0-9a-f]{24}$'),
    status         VARCHAR(20) NOT NULL DEFAULT 'pending'
                   CONSTRAINT ck_adoption_requests_status
                   CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    message        TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Un adoptante no puede tener dos solicitudes pendientes para la misma mascota
CREATE UNIQUE INDEX IF NOT EXISTS uq_adoption_requests_pending
    ON adoption_requests (adopter_id, pet_id)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS ix_adoption_requests_foundation_status
    ON adoption_requests (foundation_id, status);

CREATE TRIGGER trg_adoption_requests_updated_at
    BEFORE UPDATE ON adoption_requests
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
--  Adopciones concretadas (una por solicitud aprobada)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS adoptions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id     BIGINT      NOT NULL UNIQUE
                   REFERENCES adoption_requests(id) ON DELETE RESTRICT,
    adopter_id     BIGINT      NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    foundation_id  BIGINT      NOT NULL REFERENCES foundations(id) ON DELETE RESTRICT,
    pet_id         CHAR(24)    NOT NULL
                   CONSTRAINT ck_adoptions_pet_id CHECK (pet_id ~ '^[0-9a-f]{24}$'),
    adopted_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes          TEXT
);

CREATE INDEX IF NOT EXISTS ix_adoptions_pet_id ON adoptions (pet_id);

COMMIT;
